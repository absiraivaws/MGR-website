/**
 * Update document title, meta tags, and JSON-LD schema dynamically
 */
function updateSEOMetadata(lang) {
  const dict = translations[lang] || translations.en;
  
  document.title = dict.seo_title;
  const metaTitleEl = document.getElementById('seo-title');
  if (metaTitleEl) metaTitleEl.innerText = dict.seo_title;
  
  const metaDesc = document.getElementById('seo-desc');
  if (metaDesc) metaDesc.setAttribute('content', dict.seo_desc);
  
  const ogTitle = document.querySelector('meta[property="og:title"]');
  if (ogTitle) ogTitle.setAttribute('content', dict.seo_title);
  
  const ogDesc = document.querySelector('meta[property="og:description"]');
  if (ogDesc) ogDesc.setAttribute('content', dict.seo_desc);

  const schemaScript = document.getElementById('seo-schema');
  if (schemaScript) {
    const schemaData = {
      "@context": "https://schema.org",
      "@type": "TravelAgency",
      "name": "Mannar Green Ride",
      "description": dict.seo_desc,
      "inLanguage": lang,
      "telephone": "+94776574418",
      "email": "mannargreenride@gmail.com",
      "address": {
        "@type": "PostalAddress",
        "addressLocality": "Mannar Town",
        "addressRegion": "Northern Province",
        "addressCountry": "LK"
      },
      "priceRange": "LKR 100 - LKR 15000",
      "currenciesAccepted": "LKR, USD, EUR"
    };
    schemaScript.textContent = JSON.stringify(schemaData, null, 2);
  }
  
  document.documentElement.lang = lang;
}

